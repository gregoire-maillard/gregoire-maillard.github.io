// Writes verbs/; returns { pages: sitemap entries, links: Map(tr → "/verbs/x.html"), cards: share cards }.
// ctx: { OUT, SITE, M, deck, notes, frame, crumbs, HOME_CRUMB, text, attr, guideLink, lastmod, fileOfRank, writeFileSync, mkdirSync, join }
export function writeVerbPages(ctx) {
  const { OUT, SITE, M, frame, crumbs, HOME_CRUMB, text, attr, guideLink, writeFileSync, mkdirSync, join } = ctx;
  const seen = new Set(), verbs = [];
  for (const c of ctx.deck) {
    if (c.pos !== "verb" || seen.has(c.tr)) continue;
    seen.add(c.tr); verbs.push(c);
    if (verbs.length === VERB_COUNT) break;
  }
  const slugs = verbs.map((c) => verbSlug(c.tr));
  if (new Set(slugs).size !== slugs.length) throw new Error("verbs: two verbs share an address");
  const links = new Map(verbs.map((c, i) => [c.tr, `/verbs/${slugs[i]}.html`]));
  const tr = (s) => `<span lang="tr">${text(s)}</span>`;
  const f = (slug, v, p) => { const r = M.form(slug, v, p); return r ? r.variants : null; };
  const cell = (vs) => (vs ? tr(vs[0]) + (vs.length > 1 ? `<span class="alt"> / ${vs.slice(1).map(text).join(" / ")}</span>` : "") : "—");
  const gloss = (c) => c.en[0].replace(/\s*\([^)]*\)/g, "").trim();
  const one = (slug, v) => { const r = M.form(slug, v, "o"); if (!r) throw new Error(`verbs: no ${slug} for ${v}`); return r.text; };

  function table(slug, v) {
    if (slug === "imperative") {
      const rows = [["sen", "imperative"], ["o", "imperative-3rd"], ["siz", "imperative"], ["onlar", "imperative-3rd"]];
      return `<table class="vb"><thead><tr><th>Person</th><th>Positive</th><th>Negative</th></tr></thead><tbody>` +
        rows.map(([p, s]) => `<tr><td class="p">${p}<small>${PERSONS.find((x) => x[0] === p)[1]}</small></td><td>${cell(f(s, v, p))}</td><td>${cell(f(s + "-negative", v, p))}</td></tr>`).join("") + "</tbody></table>";
    }
    const persons = slug === "optative" ? PERSONS.filter((x) => x[0] === "ben" || x[0] === "biz") : PERSONS;
    const cols = [["Positive", slug], ["Negative", slug + "-negative"], ["Question", slug + "-question"]]
      .filter(([, s]) => persons.some(([p]) => f(s, v, p)));
    return `<table class="vb"><thead><tr><th>Person</th>${cols.map(([h]) => `<th>${h}</th>`).join("")}</tr></thead><tbody>` +
      persons.map(([p, en]) => `<tr><td class="p">${p}<small>${en}</small></td>${cols.map(([, s]) => `<td>${cell(f(s, v, p))}</td>`).join("")}</tr>`).join("") +
      "</tbody></table>";
  }

  // notes worked out from the engine's lexicon, with real forms
  function notesFor(c) {
    const v = c.tr, words = v.split(" "), last = words[words.length - 1], stem = last.slice(0, -3), out = [], L = M.LEX;
    const said = (c.note || "").toLocaleLowerCase("tr");          // what the card's note already says: don't repeat it
    const aor = one("aorist", v), pres = one("present-continuous", v);
    const etWord = words.length === 1 && L.etCompounds.some((x) => stem === x + "et");   // hissetmek, kaybetmek: one word built on etmek
    if (words.length > 1) out.push(`Only ${tr(last)} is conjugated; ${tr(words.slice(0, -1).join(" "))} stays as it is: ${tr(one("past", v))}.`);
    if (!said.includes(aor.split(" ").pop())) {
      if (etWord) out.push(`Written as one word but built on ${tr("etmek")}, so it conjugates like it: aorist ${tr(aor)}.`);
      else if (L.aorIr.includes(stem)) out.push(`One of the 13 one-syllable verbs whose aorist takes -Ir: ${tr(aor)}, not -Ar.`);
      else if (M.syllables(stem) === 1 && !M.isVowel(stem.slice(-1))) out.push(`A one-syllable stem, so the aorist takes -Ar: ${tr(aor)}.`);
      else if (M.isVowel(stem.slice(-1))) out.push(`The stem ends in a vowel, so the aorist is just -r: ${tr(aor)}; the future and the ability forms take a buffer y: ${tr(one("future", v))}.`);
      else out.push(`The aorist of a stem of two or more syllables takes -Ir: ${tr(aor)}.`);
    }
    const present = said.includes(pres.split(" ").pop());
    if (!present && (L.verbSoft[stem] || stem === "et" || etWord))
      out.push(`The final t becomes d before a vowel: ${tr(pres)}, ${tr(one("future", v))}, but ${tr(one("past", v))}.`);
    if (!present && (stem === "de" || stem === "ye")) out.push(`The e of ${tr(stem + "-")} becomes i before y: ${tr(pres)}, ${tr(one("future", v))}.`);
    return out;
  }

  mkdirSync(join(OUT, "verbs"), { recursive: true });
  const pages = [], cards = [];
  verbs.forEach((c, i) => {
    const v = c.tr, slug = slugs[i], en = gloss(c), prev = verbs[i - 1], next = verbs[i + 1];
    const cap = v.charAt(0).toLocaleUpperCase("tr") + v.slice(1);
    let title = `${cap} conjugation in Turkish (${en})`;
    if (title.length > 60) title = `${cap} conjugation (${en})`;
    if (title.length > 60) title = `${cap} conjugation in Turkish`;
    const key = { present: one("present-continuous", v), past: one("past", v), future: one("future", v), aorist: one("aorist", v) };
    const facts = [["Infinitive", v], ["Stem", v.replace(/m[ae]k$/, "-")], ["Present", key.present], ["Past", key.past], ["Future", key.future],
      ["Aorist", `${key.aorist} · ${one("aorist-negative", v)}`]];
    const sections = TENSES.map(([s, name, suf, what, gp]) => {
      const g = guideLink(gp);
      return `        <section class="vb-sec" id="${s}" aria-labelledby="h-${s}">
          <h2 id="h-${s}">${text(name)}<code>${text(suf)}</code></h2>
          <p class="vb-what">${text(what)}${g ? ` <a href="${g.href}">Learn it: ${text(g.unit)}</a>` : ""}</p>
          <div class="vb-scroll">${table(s, v)}</div>
        </section>`;
    }).join("\n");
    const note = ctx.notes[c.rank - 1];
    const body = `      <p class="wl-intro"><b lang="tr">${text(v)}</b>: ${c.en.map(text).join("; ")}. Below, every common tense and mood of ${tr(v)}, with the six persons in the positive, the negative and the question.</p>
      <div class="vb-facts">${facts.map(([k, x]) => `<div><span>${k}</span><b lang="tr">${text(x)}</b></div>`).join("")}</div>
      <div class="ex vb-ex"><p class="tr" lang="tr">${text(c.ex.tr)}</p><p class="en">${text(c.ex.en)}</p></div>
      <ul class="vb-notes">${notesFor(c).map((n) => `<li>${n}</li>`).join("")}${note ? `<li>${note}</li>` : ""}</ul>
      <p class="wl-cta">Practise ${tr(v)} with the <a href="/turkishcards.html">flashcards</a>, or see every suffix on one page in the <a href="/grammar-cheat-sheet.html">grammar cheat sheet</a>.</p>
      <nav class="wl-pager" aria-label="Tenses on this page">${TENSES.map(([s, name]) => `<a href="#${s}">${text(name)}</a>`).join("")}</nav>
      <div class="vb-grid">
${sections}
      </div>
      <nav class="wl-next" aria-label="Previous and next verb">${prev ? `<a href="${links.get(prev.tr)}" rel="prev">← ${tr(prev.tr)}</a>` : `<a href="/verbs/">← All 100 verbs</a>`}${next ? `<a href="${links.get(next.tr)}" rel="next">${tr(next.tr)} →</a>` : `<a href="/verbs/">All 100 verbs →</a>`}</nav>
      <section class="wl-about" aria-labelledby="about-h">
        <h2 id="about-h">About these tables</h2>
        <p>Suffixes are written as in the course: A stands for a or e, I for ı, i, u or ü, D for d or t, and letters in brackets are used only after a vowel (y) or a consonant (I). The forms are built by Daily Turkish's own conjugation engine, which is tested against more than 1,100 forms typed by hand from the written standard. The question particle mi is written separately and follows vowel harmony.</p>
      </section>`;
    const m = {
      title, h1: `${v}: conjugation`, kicker: `<a href="/verbs/">Turkish verbs</a>`,
      description: `Conjugation of ${v} (${en}) in Turkish: present ${key.present}, past ${key.past}, future ${key.future}, aorist ${key.aorist}, and must, can, if, let's and the imperative, positive, negative and question.`,
      canonical: `${SITE}/verbs/${slug}.html`, css: VERBS_CSS,
      ld: crumbs([HOME_CRUMB, ["Turkish verbs", SITE + "/verbs/"], [v, `${SITE}/verbs/${slug}.html`]]), body
    };
    writeFileSync(join(OUT, "verbs", slug + ".html"), frame(m));
    pages.push({ loc: m.canonical, lastmod: ctx.lastmod([ctx.fileOfRank(c.rank), "assets/js/turkish-morph.js", "scripts/turkish/static-verbs.mjs"]) });
    cards.push({ file: `verbs/${slug}.html`, name: `verb-${slug}`, level: c.level, kicker: "Turkish verb · conjugation", title: v, sub: en, subTr: false,
      alt: `Daily Turkish · ${v} (${en}): conjugation` });
  });

  const rows = verbs.map((c, i) => `          <tr><td class="n">${i + 1}</td><td class="v"><a href="${links.get(c.tr)}" lang="tr">${text(c.tr)}</a></td><td>${text(gloss(c))}</td>` +
    `<td class="f hide-s">${tr(one("present-continuous", c.tr))}</td><td class="f hide-s">${tr(one("past", c.tr))}</td><td class="f">${tr(one("aorist", c.tr))}</td></tr>`).join("\n");
  const hub = {
    title: "100 most common Turkish verbs, conjugated", h1: "The 100 most common Turkish verbs",
    description: "The 100 most common Turkish verbs with full conjugation tables: present, past, future, aorist, -mış, must, can, if and the imperative, positive, negative and question.",
    canonical: `${SITE}/verbs/`, kicker: "Turkish · Verbs", css: VERBS_CSS,
    ld: crumbs([HOME_CRUMB, ["Turkish verbs", SITE + "/verbs/"]]),
    body: `      <p class="wl-intro">The 100 verbs you'll meet most often in Turkish, in order of frequency in film and TV dialogue. Each page has the key forms, notes on what's irregular, and full tables for 13 tenses and moods. The forms below are for o (he, she, it).</p>
      <p class="wl-cta">All the suffixes on one page: the <a href="/grammar-cheat-sheet.html">grammar cheat sheet</a>. The 1,000 most common words: the <a href="/words/">word list</a>.</p>
      <table class="vl">
        <thead><tr><th>#</th><th>Verb</th><th>Meaning</th><th class="hide-s">Present</th><th class="hide-s">Past</th><th>Aorist</th></tr></thead>
        <tbody>
${rows}
        </tbody>
      </table>`
  };
  writeFileSync(join(OUT, "verbs", "index.html"), frame(hub));
  pages.unshift({ loc: hub.canonical, lastmod: ctx.lastmod([...new Set(verbs.map((c) => ctx.fileOfRank(c.rank)))].concat(["assets/js/turkish-morph.js", "scripts/turkish/static-verbs.mjs"])) });
  cards.unshift({ file: "verbs/index.html", name: "verbs", kicker: "Turkish verbs", title: "The 100 most common Turkish verbs, conjugated",
    sub: verbs.slice(0, 6).map((c) => c.tr).join(", ") + "…", subTr: true, alt: "Daily Turkish · The 100 most common Turkish verbs, conjugated" });
  return { pages, links, cards };
}
