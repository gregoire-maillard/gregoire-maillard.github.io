export const VERB_COUNT = 100;
const PERSONS = [["ben", "I"], ["sen", "you"], ["o", "he, she, it"], ["biz", "we"], ["siz", "you (pl., formal)"], ["onlar", "they"]];

// [form slug, name, suffix (course notation), what it's for, grammar point the table links to]
